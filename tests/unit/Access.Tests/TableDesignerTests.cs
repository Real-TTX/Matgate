using Matgate.Models;
using Matgate.Services.Database;
using Xunit;

namespace Matgate.Access.Tests;

// The table designer's statements: what a change of a table becomes, on each server.
public sealed class TableDesignerTests
{
    private static readonly DbTableInfo Customers = new(
        [
            new DbColumn("id", "integer", false, null, true, true),
            new DbColumn("name", "character varying(80)", false, null, false, false),
            new DbColumn("city", "character varying(80)", true, null, false, false),
        ],
        [
            new DbIndex("customers_pkey", "id", true, true, "CREATE UNIQUE INDEX customers_pkey ON public.customers USING btree (id)"),
            new DbIndex("ix_city", "city", false, false, "CREATE INDEX ix_city ON public.customers USING btree (city)"),
        ],
        []);

    private static List<DesignColumn> Same() =>
    [
        new("id", "id", "integer", false, null, true, true),
        new("name", "name", "character varying(80)", false, null, false, false),
        new("city", "city", "character varying(80)", true, null, false, false),
    ];

    private static List<string> Postgres(TableDesign design, string? original = "customers") =>
        TableDesigner.Statements(ServerProtocol.Postgres, "public", original, original is null ? null : Customers, design, false);

    [Fact]
    public void Nothing_changed_nothing_to_run() =>
        Assert.Empty(Postgres(new TableDesign("customers", Same(), [new DesignIndex("ix_city", "ix_city", "city", false)], [])));

    [Fact]
    public void A_new_table_on_each_server()
    {
        var design = new TableDesign("orders",
            [new DesignColumn("", "id", "int", false, null, true, true), new DesignColumn("", "total", "decimal(10,2)", true, "0", false, false)],
            [new DesignIndex("", "", "total", false)],
            [new DesignForeignKey("", "", "id", "customers", "id", "CASCADE", "")]);
        var postgres = TableDesigner.Statements(ServerProtocol.Postgres, "public", null, null, design, false);
        Assert.Equal("CREATE TABLE \"public\".\"orders\" (\n    \"id\" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"total\" decimal(10,2) NULL DEFAULT 0,\n    CONSTRAINT \"orders_pkey\" PRIMARY KEY (\"id\")\n);", postgres[0]);
        Assert.Equal("CREATE INDEX \"IX_orders_total\" ON \"public\".\"orders\" (\"total\");", postgres[1]);
        Assert.Equal("ALTER TABLE \"public\".\"orders\" ADD CONSTRAINT \"FK_orders_customers\" FOREIGN KEY (\"id\") REFERENCES \"customers\" (\"id\") ON DELETE CASCADE;", postgres[2]);
        var sqlServer = TableDesigner.Statements(ServerProtocol.MsSql, "dbo", null, null, design, false);
        Assert.Contains("[id] int IDENTITY(1,1) NOT NULL", sqlServer[0]);
        Assert.Contains("CONSTRAINT [PK_orders] PRIMARY KEY ([id])", sqlServer[0]);
        var mysql = TableDesigner.Statements(ServerProtocol.MySql, "shop", null, null, design, false);
        Assert.Contains("`id` int NOT NULL AUTO_INCREMENT", mysql[0]);
        Assert.Contains("    PRIMARY KEY (`id`)", mysql[0]);
    }

    [Fact]
    public void A_renamed_column_is_renamed_not_dropped()
    {
        var columns = Same();
        columns[2] = columns[2] with { Name = "town" };
        var statements = Postgres(new TableDesign("customers", columns, [new DesignIndex("ix_city", "ix_city", "town", false)], []));
        Assert.Equal(["ALTER TABLE \"public\".\"customers\" RENAME COLUMN \"city\" TO \"town\";"], statements);
    }

    [Fact]
    public void Dropped_changed_and_added_columns()
    {
        var columns = Same();
        columns.RemoveAt(2);
        columns[1] = columns[1] with { Type = "text", Nullable = true, Default = "'?'" };
        columns.Add(new DesignColumn("", "since", "date", true, null, false, false));
        var statements = Postgres(new TableDesign("customers", columns, [], []));
        Assert.Equal(
        [
            "DROP INDEX \"public\".\"ix_city\";",
            "ALTER TABLE \"public\".\"customers\" DROP COLUMN \"city\";",
            "ALTER TABLE \"public\".\"customers\" ALTER COLUMN \"name\" TYPE text USING \"name\"::text;",
            "ALTER TABLE \"public\".\"customers\" ALTER COLUMN \"name\" DROP NOT NULL;",
            "ALTER TABLE \"public\".\"customers\" ALTER COLUMN \"name\" SET DEFAULT '?';",
            "ALTER TABLE \"public\".\"customers\" ADD COLUMN \"since\" date NULL;",
        ], statements);
    }

    [Fact]
    public void A_new_primary_key_replaces_the_old_one()
    {
        var columns = Same();
        columns[1] = columns[1] with { PrimaryKey = true };
        var statements = Postgres(new TableDesign("customers", columns, [new DesignIndex("ix_city", "ix_city", "city", false)], []));
        Assert.Equal(
        [
            "ALTER TABLE \"public\".\"customers\" DROP CONSTRAINT \"customers_pkey\";",
            "ALTER TABLE \"public\".\"customers\" ADD CONSTRAINT \"customers_pkey\" PRIMARY KEY (\"id\", \"name\");",
        ], statements);
    }

    [Fact]
    public void A_renamed_table_is_renamed_last()
    {
        var statements = Postgres(new TableDesign("clients", Same(), [new DesignIndex("ix_city", "ix_city", "city", true)], []));
        Assert.Equal(
        [
            "DROP INDEX \"public\".\"ix_city\";",
            "CREATE UNIQUE INDEX \"ix_city\" ON \"public\".\"customers\" (\"city\");",
            "ALTER TABLE \"public\".\"customers\" RENAME TO \"clients\";",
        ], statements);
    }

    [Fact]
    public void Sql_server_and_mysql_say_it_in_their_own_words()
    {
        var columns = Same().Select(column => column with { Type = column.Type.Replace("character varying", "nvarchar") }).ToList();
        columns[2] = columns[2] with { Name = "town", Type = "nvarchar(120)" };
        var info = Customers with { Columns = [.. Customers.Columns.Select(column => column with { Type = column.Type.Replace("character varying", "nvarchar") })] };
        var sqlServer = TableDesigner.Statements(ServerProtocol.MsSql, "dbo", "customers", info, new TableDesign("customers", columns, [new DesignIndex("ix_city", "ix_city", "town", false)], []), false);
        Assert.Equal("EXEC sp_rename 'dbo.customers.city', 'town', 'COLUMN';", sqlServer[0]);
        Assert.Equal("ALTER TABLE [dbo].[customers] ALTER COLUMN [town] nvarchar(120) NULL;", sqlServer[1]);
        var mysql = TableDesigner.Statements(ServerProtocol.MySql, "shop", "customers", info, new TableDesign("customers", columns, [new DesignIndex("ix_city", "ix_city", "town", false)], []), false);
        Assert.Equal("ALTER TABLE `shop`.`customers` RENAME COLUMN `city` TO `town`;", mysql[0]);
        Assert.Equal("ALTER TABLE `shop`.`customers` MODIFY COLUMN `town` nvarchar(120) NULL;", mysql[1]);
    }

    [Theory]
    [InlineData("int; DROP TABLE x")]
    [InlineData("varchar(10)) --")]
    [InlineData("")]
    public void A_type_must_look_like_a_type(string type)
    {
        var columns = Same();
        columns[1] = columns[1] with { Type = type };
        Assert.Throws<DatabaseException>(() => Postgres(new TableDesign("customers", columns, [], [])));
    }

    [Fact]
    public void Types_with_spaces_lengths_and_arrays_are_types()
    {
        var columns = new List<DesignColumn>
        {
            new("", "a", "timestamp with time zone", true, null, false, false),
            new("", "b", "numeric(10, 2)", true, null, false, false),
            new("", "c", "nvarchar(max)", true, null, false, false),
            new("", "d", "int[]", true, null, false, false),
        };
        Assert.Single(TableDesigner.Statements(ServerProtocol.Postgres, "public", null, null, new TableDesign("t", columns, [], []), false));
    }
}
