using System.Text.RegularExpressions;
using Matgate.Models;

namespace Matgate.Services.Database;

// A table as the designer has it: its name, its columns, indexes and foreign keys. OriginalName says which column
// of the table as it is a column was (empty: a new one) - that is how a rename is told from a drop and an add.
public sealed record DesignColumn(string OriginalName, string Name, string Type, bool Nullable, string? Default, bool PrimaryKey, bool Identity);

public sealed record DesignIndex(string OriginalName, string Name, string Columns, bool Unique);

public sealed record DesignForeignKey(string OriginalName, string Name, string Columns, string ReferencedTable, string ReferencedColumns, string OnDelete, string OnUpdate);

public sealed record TableDesign(string Name, IReadOnlyList<DesignColumn> Columns, IReadOnlyList<DesignIndex> Indexes, IReadOnlyList<DesignForeignKey> ForeignKeys);

// From a table as it is (or none: a new table) and as the designer wants it, the statements that get there - for
// each server in its own words. In an order that works: what goes is dropped first (foreign keys, indexes, the
// primary key, columns), then columns are renamed, changed and added, then the primary key, indexes and foreign keys
// are made, and the table is renamed last. Names are quoted; a type must look like a type; a default is taken as
// written (it is an expression) - whoever designs a table may run any statement on it anyway.
public static partial class TableDesigner
{
    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_ ]*(\(\s*(\d+|max|MAX)(\s*,\s*\d+)?\s*\))?(\s*\[\])?$")]
    private static partial Regex TypePattern();

    private static readonly string[] Actions = ["NO ACTION", "CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT"];

    public static List<string> Statements(ServerProtocol protocol, string schema, string? originalName, DbTableInfo? original, TableDesign design, bool german)
    {
        var dialect = DatabaseGateway.DialectOf(protocol);
        string Fail(string de, string en) => throw new DatabaseException(german ? de : en);
        if (string.IsNullOrWhiteSpace(design.Name))
        {
            Fail("Die Tabelle braucht einen Namen.", "The table needs a name.");
        }

        var columns = design.Columns.Where(column => !string.IsNullOrWhiteSpace(column.Name)).ToList();
        if (columns.Count == 0)
        {
            Fail("Die Tabelle braucht mindestens eine Spalte.", "The table needs at least one column.");
        }

        foreach (var column in columns)
        {
            if (!TypePattern().IsMatch(column.Type.Trim()))
            {
                Fail($"„{column.Type}“ ist kein Typ (Spalte {column.Name}).", $"\"{column.Type}\" is not a type (column {column.Name}).");
            }
        }

        var duplicate = columns.GroupBy(column => column.Name.Trim(), StringComparer.OrdinalIgnoreCase).FirstOrDefault(group => group.Count() > 1);
        if (duplicate is not null)
        {
            Fail($"Die Spalte „{duplicate.Key}“ steht zweimal da.", $"The column \"{duplicate.Key}\" is there twice.");
        }

        var tableName = design.Name.Trim();
        var isNew = original is null || string.IsNullOrEmpty(originalName);
        var table = dialect.Table(schema, isNew ? tableName : originalName!);
        string Q(string name) => dialect.Quote(name.Trim());
        string List(string names) => string.Join(", ", names.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries).Select(Q));
        string Action(string value)
        {
            var upper = (value ?? "").Trim().ToUpperInvariant();
            return Actions.Contains(upper) ? upper : "NO ACTION";
        }

        string Definition(DesignColumn column)
        {
            var text = Q(column.Name) + " " + column.Type.Trim();
            if (column.Identity)
            {
                text += protocol switch
                {
                    ServerProtocol.MsSql => " IDENTITY(1,1)",
                    ServerProtocol.MySql => "",
                    _ => " GENERATED BY DEFAULT AS IDENTITY",
                };
            }

            text += column.Nullable && !column.PrimaryKey ? " NULL" : " NOT NULL";
            if (!string.IsNullOrWhiteSpace(column.Default) && !column.Identity)
            {
                text += " DEFAULT " + column.Default.Trim();
            }

            if (column.Identity && protocol == ServerProtocol.MySql)
            {
                text += " AUTO_INCREMENT";
            }

            return text;
        }

        var primary = columns.Where(column => column.PrimaryKey).Select(column => column.Name.Trim()).ToList();
        var primaryName = protocol switch
        {
            ServerProtocol.Postgres => tableName + "_pkey",
            ServerProtocol.MsSql => "PK_" + tableName,
            _ => "PRIMARY",
        };
        string IndexName(DesignIndex index) => string.IsNullOrWhiteSpace(index.Name)
            ? (index.Unique ? "UX_" : "IX_") + tableName + "_" + string.Join("_", index.Columns.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
            : index.Name.Trim();
        string KeyName(DesignForeignKey key) => string.IsNullOrWhiteSpace(key.Name)
            ? "FK_" + tableName + "_" + key.ReferencedTable.Split('.').Last().Trim('"', '`', '[', ']')
            : key.Name.Trim();
        string ReferencedTable(string name)
        {
            // "shop.customers", "customers" or already quoted: each part quoted once.
            var parts = name.Split('.', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
            return string.Join(".", parts.Select(part => part.StartsWith('"') || part.StartsWith('`') || part.StartsWith('[') ? part : Q(part)));
        }

        string CreateIndex(DesignIndex index) =>
            "CREATE " + (index.Unique ? "UNIQUE " : "") + "INDEX " + Q(IndexName(index)) + " ON " + table + " (" + List(index.Columns) + ");";
        string AddForeignKey(DesignForeignKey key) =>
            "ALTER TABLE " + table + " ADD CONSTRAINT " + Q(KeyName(key)) + " FOREIGN KEY (" + List(key.Columns) + ") REFERENCES "
            + ReferencedTable(key.ReferencedTable) + " (" + List(key.ReferencedColumns) + ")"
            + (Action(key.OnDelete) == "NO ACTION" ? "" : " ON DELETE " + Action(key.OnDelete))
            + (Action(key.OnUpdate) == "NO ACTION" ? "" : " ON UPDATE " + Action(key.OnUpdate)) + ";";

        var statements = new List<string>();
        if (isNew)
        {
            var lines = columns.Select(column => "    " + Definition(column)).ToList();
            if (primary.Count > 0)
            {
                lines.Add("    " + (protocol == ServerProtocol.MySql ? "" : "CONSTRAINT " + Q(primaryName) + " ") + "PRIMARY KEY (" + string.Join(", ", primary.Select(Q)) + ")");
            }

            statements.Add("CREATE TABLE " + table + " (\n" + string.Join(",\n", lines) + "\n);");
            statements.AddRange(design.Indexes.Where(index => !string.IsNullOrWhiteSpace(index.Columns)).Select(CreateIndex));
            statements.AddRange(design.ForeignKeys.Where(key => !string.IsNullOrWhiteSpace(key.Columns)).Select(AddForeignKey));
            return statements;
        }

        // ---- an existing table: what changed
        var before = original!;
        var oldColumns = before.Columns.ToDictionary(column => column.Name, StringComparer.Ordinal);
        var kept = columns.Where(column => column.OriginalName.Length > 0 && oldColumns.ContainsKey(column.OriginalName)).ToList();
        var keptNames = kept.Select(column => column.OriginalName).ToHashSet(StringComparer.Ordinal);
        var dropped = before.Columns.Where(column => !keptNames.Contains(column.Name)).ToList();
        var added = columns.Where(column => column.OriginalName.Length == 0 || !oldColumns.ContainsKey(column.OriginalName)).ToList();
        var oldPrimary = before.Indexes.FirstOrDefault(index => index.Primary);
        var oldPrimaryColumns = before.Columns.Where(column => column.PrimaryKey).Select(column => column.Name).ToList();
        // The primary key in the names the columns have after the renames.
        var newPrimaryAsOld = columns.Where(column => column.PrimaryKey).Select(column => column.OriginalName.Length > 0 ? column.OriginalName : "\0" + column.Name).ToList();
        var primaryChanged = !oldPrimaryColumns.SequenceEqual(newPrimaryAsOld, StringComparer.Ordinal);
        var oldIndexes = before.Indexes.Where(index => !index.Primary).ToList();
        var keptIndexes = design.Indexes.Where(index => index.OriginalName.Length > 0).Select(index => index.OriginalName).ToHashSet(StringComparer.Ordinal);
        var oldKeys = before.ForeignKeys.ToList();
        var keptKeys = design.ForeignKeys.Where(key => key.OriginalName.Length > 0).Select(key => key.OriginalName).ToHashSet(StringComparer.Ordinal);

        // Columns of an index or key in the names they had before: a renamed column is renamed in them by the
        // server itself, so that alone changes nothing.
        var formerName = kept.ToDictionary(column => column.Name.Trim(), column => column.OriginalName, StringComparer.Ordinal);
        string Former(string names) => string.Join(",", names.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)
            .Select(name => formerName.TryGetValue(name, out var was) ? was : name));

        // A kept index or key that was changed is dropped and made again.
        bool IndexChanged(DesignIndex index)
        {
            var old = oldIndexes.FirstOrDefault(candidate => candidate.Name == index.OriginalName);
            return old is null || old.Unique != index.Unique || IndexName(index) != old.Name
                || !string.Equals(Normalize(old.Columns), Normalize(Former(index.Columns)), StringComparison.Ordinal);
        }

        bool KeyChanged(DesignForeignKey key)
        {
            var old = oldKeys.FirstOrDefault(candidate => candidate.Name == key.OriginalName);
            return old is null || KeyName(key) != old.Name || Normalize(old.Columns) != Normalize(Former(key.Columns))
                || Normalize(old.ReferencedColumns) != Normalize(key.ReferencedColumns)
                || Normalize(old.ReferencedTable.Replace("\"", "").Replace("`", "").Replace("[", "").Replace("]", "")) != Normalize(key.ReferencedTable.Replace("\"", "").Replace("`", "").Replace("[", "").Replace("]", ""))
                || Action(old.OnDelete) != Action(key.OnDelete) || Action(old.OnUpdate) != Action(key.OnUpdate);
        }

        var dropKeys = oldKeys.Where(key => !keptKeys.Contains(key.Name) || KeyChanged(design.ForeignKeys.First(candidate => candidate.OriginalName == key.Name))).ToList();
        var dropIndexes = oldIndexes.Where(index => !keptIndexes.Contains(index.Name) || IndexChanged(design.Indexes.First(candidate => candidate.OriginalName == index.Name))).ToList();
        foreach (var key in dropKeys)
        {
            statements.Add("ALTER TABLE " + table + (protocol == ServerProtocol.MySql ? " DROP FOREIGN KEY " : " DROP CONSTRAINT ") + Q(key.Name) + ";");
        }

        foreach (var index in dropIndexes)
        {
            // A unique key made as a constraint is dropped as one; an index as an index.
            statements.Add(protocol switch
            {
                ServerProtocol.Postgres => index.Unique && index.Definition.Length > 0 && !index.Definition.Contains("INDEX", StringComparison.OrdinalIgnoreCase)
                    ? "ALTER TABLE " + table + " DROP CONSTRAINT " + Q(index.Name) + ";"
                    : "DROP INDEX " + (schema.Length > 0 ? Q(schema) + "." : "") + Q(index.Name) + ";",
                _ => "DROP INDEX " + Q(index.Name) + " ON " + table + ";",
            });
        }

        if (primaryChanged && oldPrimary is not null)
        {
            statements.Add(protocol == ServerProtocol.MySql
                ? "ALTER TABLE " + table + " DROP PRIMARY KEY;"
                : "ALTER TABLE " + table + " DROP CONSTRAINT " + Q(oldPrimary.Name) + ";");
        }

        foreach (var column in dropped)
        {
            statements.Add("ALTER TABLE " + table + " DROP COLUMN " + Q(column.Name) + ";");
        }

        foreach (var column in kept.Where(column => column.Name.Trim() != column.OriginalName))
        {
            statements.Add(protocol == ServerProtocol.MsSql
                ? "EXEC sp_rename '" + (schema + "." + (originalName ?? tableName) + "." + column.OriginalName).Replace("'", "''") + "', '" + column.Name.Trim().Replace("'", "''") + "', 'COLUMN';"
                : "ALTER TABLE " + table + " RENAME COLUMN " + Q(column.OriginalName) + " TO " + Q(column.Name) + ";");
        }

        foreach (var column in kept)
        {
            var old = oldColumns[column.OriginalName];
            var typeChanged = !string.Equals(Normalize(old.Type), Normalize(column.Type), StringComparison.OrdinalIgnoreCase);
            var nullable = column.Nullable && !column.PrimaryKey;
            var nullChanged = old.Nullable != nullable;
            var oldDefault = old.Identity ? null : NormalizeDefault(old.Default);
            var newDefault = column.Identity ? null : NormalizeDefault(column.Default);
            var defaultChanged = !string.Equals(oldDefault, newDefault, StringComparison.Ordinal);
            var identityChanged = old.Identity != column.Identity;
            if (!typeChanged && !nullChanged && !defaultChanged && !identityChanged)
            {
                continue;
            }

            var name = Q(column.Name);
            switch (protocol)
            {
                case ServerProtocol.MySql:
                    // MySQL says everything about a column at once.
                    statements.Add("ALTER TABLE " + table + " MODIFY COLUMN " + Definition(column) + ";");
                    break;
                case ServerProtocol.Postgres:
                    if (typeChanged)
                    {
                        statements.Add("ALTER TABLE " + table + " ALTER COLUMN " + name + " TYPE " + column.Type.Trim() + " USING " + name + "::" + column.Type.Trim() + ";");
                    }

                    if (nullChanged)
                    {
                        statements.Add("ALTER TABLE " + table + " ALTER COLUMN " + name + (nullable ? " DROP NOT NULL;" : " SET NOT NULL;"));
                    }

                    if (identityChanged)
                    {
                        statements.Add("ALTER TABLE " + table + " ALTER COLUMN " + name + (column.Identity ? " ADD GENERATED BY DEFAULT AS IDENTITY;" : " DROP IDENTITY IF EXISTS;"));
                    }

                    if (defaultChanged && !column.Identity)
                    {
                        statements.Add("ALTER TABLE " + table + " ALTER COLUMN " + name + (newDefault is null ? " DROP DEFAULT;" : " SET DEFAULT " + newDefault + ";"));
                    }

                    break;
                default:
                    if (identityChanged)
                    {
                        Fail($"SQL Server kann eine bestehende Spalte nicht nachträglich zur automatischen Nummer machen (oder umgekehrt): {column.Name}.",
                            $"SQL Server cannot turn an existing column into an identity (or back): {column.Name}.");
                    }

                    if (typeChanged || nullChanged)
                    {
                        statements.Add("ALTER TABLE " + table + " ALTER COLUMN " + name + " " + column.Type.Trim() + (nullable ? " NULL;" : " NOT NULL;"));
                    }

                    if (defaultChanged)
                    {
                        // A default is a constraint with a name of its own there: found and dropped first.
                        statements.Add("DECLARE @default sysname = (SELECT dc.name FROM sys.default_constraints dc WHERE dc.parent_object_id = OBJECT_ID('"
                            + table.Replace("'", "''") + "') AND dc.parent_column_id = COLUMNPROPERTY(OBJECT_ID('" + table.Replace("'", "''") + "'), '"
                            + column.Name.Trim().Replace("'", "''") + "', 'ColumnId')); IF @default IS NOT NULL EXEC('ALTER TABLE " + table.Replace("'", "''")
                            + " DROP CONSTRAINT [' + @default + ']');");
                        if (newDefault is not null)
                        {
                            statements.Add("ALTER TABLE " + table + " ADD DEFAULT " + newDefault + " FOR " + name + ";");
                        }
                    }

                    break;
            }
        }

        foreach (var column in added)
        {
            statements.Add("ALTER TABLE " + table + " ADD " + (protocol == ServerProtocol.MsSql ? "" : "COLUMN ") + Definition(column) + ";");
        }

        if (primaryChanged && primary.Count > 0)
        {
            statements.Add(protocol == ServerProtocol.MySql
                ? "ALTER TABLE " + table + " ADD PRIMARY KEY (" + string.Join(", ", primary.Select(Q)) + ");"
                : "ALTER TABLE " + table + " ADD CONSTRAINT " + Q(oldPrimary?.Name ?? primaryName) + " PRIMARY KEY (" + string.Join(", ", primary.Select(Q)) + ");");
        }

        statements.AddRange(design.Indexes
            .Where(index => !string.IsNullOrWhiteSpace(index.Columns) && (index.OriginalName.Length == 0 || dropIndexes.Any(old => old.Name == index.OriginalName)))
            .Select(CreateIndex));
        statements.AddRange(design.ForeignKeys
            .Where(key => !string.IsNullOrWhiteSpace(key.Columns) && (key.OriginalName.Length == 0 || dropKeys.Any(old => old.Name == key.OriginalName)))
            .Select(AddForeignKey));

        if (originalName is not null && tableName != originalName)
        {
            statements.Add(protocol switch
            {
                ServerProtocol.MsSql => "EXEC sp_rename '" + (schema + "." + originalName).Replace("'", "''") + "', '" + tableName.Replace("'", "''") + "';",
                ServerProtocol.MySql => "RENAME TABLE " + table + " TO " + dialect.Table(schema, tableName) + ";",
                _ => "ALTER TABLE " + table + " RENAME TO " + Q(tableName) + ";",
            });
        }

        return statements;
    }

    private static string Normalize(string? value) =>
        Regex.Replace((value ?? "").Trim(), @"\s+", " ").Replace(" ,", ",").Replace(", ", ",").ToLowerInvariant();

    // A default as the server shows it and as the designer writes it come apart in brackets only ("((0))" on SQL
    // Server, "'x'::text" on PostgreSQL stays as it is): the outer brackets do not make a change.
    private static string? NormalizeDefault(string? value)
    {
        var text = (value ?? "").Trim();
        while (text.Length > 1 && text[0] == '(' && text[^1] == ')' && Balanced(text[1..^1]))
        {
            text = text[1..^1].Trim();
        }

        return text.Length == 0 ? null : text;
    }

    private static bool Balanced(string text)
    {
        var depth = 0;
        foreach (var character in text)
        {
            depth += character == '(' ? 1 : character == ')' ? -1 : 0;
            if (depth < 0)
            {
                return false;
            }
        }

        return depth == 0;
    }
}
